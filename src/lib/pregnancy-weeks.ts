/** Информация о неделе, которая идёт сейчас. До 4-й недели — null. */
export function weekInfo(week: number): WeekInfo | null {
  if (week < 4) return null;
  return WEEKS[Math.min(week, 40)];
}

/** Короткие подсказки по сроку — что обычно делают в это время. Конкретику обсудить с врачом. */
export function weekTips(week: number): string[] {
  const tips: string[] = [];
  if (week <= 12) {
    tips.push("Обычно советуют принимать фолиевую кислоту в первом триместре — уточните дозу у врача.");
    tips.push("Если ещё не встали на учёт, запишитесь к врачу. Лекарства, даже привычные, принимайте только после консультации.");
  }
  if (week >= 10 && week <= 14) tips.push("Во многих странах на 11–13 неделе проводят первое скрининговое УЗИ.");
  if (week >= 14 && week <= 27) tips.push("Если врач не против, умеренная активность — прогулки, плавание — обычно полезна.");
  if (week >= 18 && week <= 21) tips.push("На 18–21 неделе обычно проводят второе скрининговое УЗИ.");
  if (week >= 24 && week <= 28) tips.push("Около 24–28 недели часто проверяют уровень сахара — спросите врача, нужен ли вам этот анализ.");
  if (week >= 24) tips.push("Узнайте, какие шевеления для вашего малыша обычны. Если они стали реже — не ждите, обратитесь к врачу.");
  if (week >= 32 && week <= 36) tips.push("Самое время собрать сумку в роддом и обсудить план родов.");
  if (week >= 37) tips.push("Держите под рукой документы и телефон роддома.");
  return tips;
}

